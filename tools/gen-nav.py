#!/usr/bin/env python3
"""Generate mkdocs.yml for the VPinWiki site.

Builds the nav from the wiki/ file tree (index.md becomes the home page)
and emits a complete MkDocs config using the Material theme.
Run from any directory; writes mkdocs.yml at the repo root.
"""
import os
import shutil
import yaml

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = "wiki"

SECTIONS = [
    ("",          "Overview"),
    ("projects",  "Projects"),
    ("concepts",  "Concepts"),
    ("sources",   "Sources"),
]


def page_items(sub):
    d = os.path.join(REPO, DOCS, sub)
    items = []
    for f in sorted(os.listdir(d)):
        if not f.endswith(".md"):
            continue
        if sub == "" and f == "index.md":
            continue  # index.md is the home page
        title = f[:-3]
        path = os.path.join(sub, f) if sub else f
        items.append({title: path})
    return items


def main():
    # Make the schema page available inside docs_dir so links to ../AGENTS.md resolve
    shutil.copy(os.path.join(REPO, "AGENTS.md"), os.path.join(REPO, DOCS, "AGENTS.md"))

    nav = [{"Home": "index.md"}, {"Schema": "AGENTS.md"}]
    for sub, label in SECTIONS:
        items = page_items(sub)
        if items:
            nav.append({label: items})

    config = {
        "site_name": "VPinWiki",
        "site_description": "Community-maintained knowledge base for the virtual pinball ecosystem (VPX, B2S, DOF, DMD, Pinscape, PinUp, SSFImpactor)",
        "site_dir": "site",
        "docs_dir": DOCS,
        "use_directory_urls": False,
        "theme": {
            "name": "material",
            "features": [
                "navigation.top",
                "navigation.sections",
                "search.share",
                "toc.follow",
            ],
            "palette": [
                {"scheme": "default", "primary": "indigo"},
                {"scheme": "slate", "primary": "indigo", "toggle": {"icon": "material/weather-night", "name": "Dark mode"}},
            ],
        },
        "plugins": [{"search": {}}],
        "markdown_extensions": [
            "admonition",
            "attr_list",
            "fenced_code",
            {"toc": {"permalink": "¶"}},
        ],
        "nav": nav,
    }

    out = os.path.join(REPO, "mkdocs.yml")
    with open(out, "w") as fh:
        fh.write("# Generated by tools/gen-nav.py — do not edit by hand.\n")
        yaml.safe_dump(config, fh, sort_keys=False, allow_unicode=True, width=100000)
    def count(entries):
        n = 0
        for s in entries:
            v = list(s.values())[0]
            n += len(v) if isinstance(v, list) else 1
        return n

    print(f"wrote {out} ({count(nav)} nav pages)")


if __name__ == "__main__":
    main()
